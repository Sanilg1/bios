// "Do the tests bite?" Removes each rule's check from a scratch copy of the server, one at a time,
// runs the test suite against it, and reports whether a test caught the missing rule.
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { join } from "node:path";

const SCRATCH = ".mutation";
const MUTANTS = [
  { rule: "R0", file: "server/app.js", find: 'if (!identity) throw new Denied("R0"', replace: 'if (false) throw new Denied("R0"' },
  { rule: "R1", file: "server/policy/engine.js", find: "if (actorSub === request.requesterSub) {", replace: "if (false) {" },
  { rule: "R2", file: "server/policy/engine.js", find: "if (otherSlot) deny(", replace: "if (false) deny(" },
  { rule: "R2 (slot once)", file: "server/policy/engine.js", find: "if (request.reviews[slot]) deny(", replace: "if (false) deny(" },
  { rule: "R3", file: "server/policy/engine.js", find: 'if (widened.length) deny("R3"', replace: 'if (false) deny("R3"' },
  { rule: "R4", file: "server/policy/engine.js", find: "!grant.purposes.includes(input.purpose)", replace: "false", all: true },
  { rule: "R5", file: "server/policy/engine.js", find: "if (inUse + gpus > grant.gpuCount) {", replace: "if (false) {" },
  { rule: "R6", file: "server/policy/engine.js", find: 'if (status === "expired") deny("R6", `${grant.id} expired at', replace: 'if (false) deny("R6", `${grant.id} expired at' },
  { rule: "R7", file: "server/policy/engine.js", find: 'if (status === "revoked") deny("R7", `${grant.id} was revoked', replace: 'if (false) deny("R7", `${grant.id} was revoked' },
  { rule: "R8", file: "server/policy/engine.js", find: "function lockGrant(grant) {", replace: "function lockGrant(grant) {\n  return grant;" },
  { rule: "R9", file: "server/policy/engine.js", find: 'if (slot === "owner" && !resource.ownerSubs.includes(actorSub)) {', replace: "if (false) {" },
  { rule: "R10", file: "server/policy/engine.js", find: "!APPROVED_IMAGES.includes(image)", replace: "false" },
  { rule: "R11 (revoke role)", file: "server/policy/engine.js", find: 'if (!hasRole(actorSub, "risk") && !isOwner) deny(', replace: "if (false) deny(" },
  { rule: "R13", file: "server/policy/engine.js", find: "if (grant.holderSub !== actorSub) deny(", replace: "if (false) deny(" },
  { rule: "Revoke kills jobs", file: "server/policy/engine.js", find: "job.killedAt = t;", replace: "" },
  {
    rule: "Score stays advisory",
    file: "server/policy/engine.js",
    find: "const scope = request.effective;",
    replace: "const scope = computeScore(state, request.requesterSub, now()).score < 30 ? { ...request.effective, durationDays: 1 } : request.effective;",
  },
];

function freshCopy() {
  rmSync(SCRATCH, { recursive: true, force: true });
  mkdirSync(SCRATCH);
  cpSync("server", join(SCRATCH, "server"), { recursive: true });
  cpSync("test", join(SCRATCH, "test"), { recursive: true });
}

function runTests() {
  const dir = join(SCRATCH, "test");
  const files = readdirSync(dir).filter((f) => f.endsWith(".test.js")).map((f) => join(dir, f));
  const run = spawnSync(process.execPath, ["--test", ...files], { encoding: "utf8" });
  const count = (key) => Number(new RegExp(`ℹ ${key} (\\d+)`).exec(run.stdout)?.[1] ?? 0);
  return { status: run.status, tests: count("tests"), failed: count("fail") };
}

// Control: the unmutated copy must pass in full, or every result below would be meaningless.
freshCopy();
const control = runTests();
if (control.status !== 0 || control.tests < 10) {
  rmSync(SCRATCH, { recursive: true, force: true });
  console.error(`Control run failed (${control.failed}/${control.tests} failing): the harness is broken, results would be meaningless.`);
  process.exit(2);
}

const results = [];
for (const mutant of MUTANTS) {
  freshCopy();
  const target = join(SCRATCH, mutant.file);
  const source = readFileSync(target, "utf8");
  if (!source.includes(mutant.find)) {
    results.push({ ...mutant, outcome: "MUTANT NOT APPLIED (pattern missing)" });
    continue;
  }
  writeFileSync(target, mutant.all ? source.replaceAll(mutant.find, mutant.replace) : source.replace(mutant.find, mutant.replace));
  const run = runTests();
  results.push({ ...mutant, outcome: run.status !== 0 ? `caught (${run.failed} of ${run.tests} tests fail)` : "SURVIVED: no test noticed" });
}
rmSync(SCRATCH, { recursive: true, force: true });

const lines = [
  "# Do the tests bite?",
  "",
  `Generated by \`node scripts/mutation-check.mjs\`. Control run with no mutation: ${control.tests} tests, all passing.`,
  "Each row then removes one rule from a scratch copy of the server and reruns the whole suite.",
  "",
  "| Rule removed | Result |",
  "|---|---|",
  ...results.map((r) => `| ${r.rule} | ${r.outcome} |`),
  "",
];
mkdirSync("samples", { recursive: true });
writeFileSync("samples/mutation-report.md", lines.join("\n"));
console.log(lines.join("\n"));
if (results.some((r) => !r.outcome.startsWith("caught"))) process.exitCode = 1;
